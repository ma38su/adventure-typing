const readingEntries = Object.entries(UI_RUBY_READINGS).sort(([left], [right]) => right.length - left.length)
const kanjiPattern = /[一-龯々〆ヶ]/

export function splitUIRuby(text: string) {
  const parts: Array<{ text: string; reading?: string }> = []
  let remaining = text
  while (remaining) {
    const entry = readingEntries.find(([word]) => remaining.startsWith(word))
    if (entry) { parts.push({ text: entry[0], reading: entry[1] }); remaining = remaining.slice(entry[0].length); continue }
    const character = remaining[0]
    const previous = parts.at(-1)
    if (previous && !previous.reading) previous.text += character
    else parts.push({ text: character })
    remaining = remaining.slice(1)
  }
  return parts
}

export function getUncoveredUIKanji(text: string) {
  return splitUIRuby(text).filter((part) => !part.reading && kanjiPattern.test(part.text)).flatMap((part) => part.text.match(/[一-龯々〆ヶ]/g) ?? []).join('')
}
